"""Branch-only distillation of an inserted-attention student from a teacher on agent trajectories.

Student: a Hugging Face Qwen3.5 parent with `archlab.architectures.qwen35_insertion` branches; the backbone is frozen.
Teacher: a stronger model with the same tokenizer, run forward-only on its own device. Data: Uni-Agent trajectory files
(trajectory.npz: prompt ids, response ids, response mask = model-generated tokens). The loss is KL(teacher || student)
over the full vocabulary at positions whose next token was generated by the policy (observations are context only).
Trajectories are split by prompt-token SHA-256 into train and a fixed evaluation set before any training.
Each run writes metrics.jsonl (train loss, evaluation KL vs the untrained parent) and the branch weights.
usage: python -m archlab.training.distill <run.json>
"""

from __future__ import annotations

import hashlib
import json
import math
import random
import sys
import time
from pathlib import Path

import numpy as np
import torch


def prompt_sha256(path: Path) -> str:
    with np.load(path) as data:
        return hashlib.sha256(np.asarray(data["traj0_prompt_ids"]).tobytes()).hexdigest()


def split(paths: list[Path], eval_fraction: float) -> tuple[list[Path], list[Path]]:
    """Task-level split by prompt-token SHA-256: identical prompts never cross train and evaluation."""
    train, evaluation = [], []
    train_keys, eval_keys = set(), set()
    for path in paths:
        key = prompt_sha256(path)
        bucket = int(hashlib.sha256(f"prompt:{key}".encode()).hexdigest(), 16) % 1000
        if bucket < eval_fraction * 1000:
            evaluation.append(path)
            eval_keys.add(key)
        else:
            train.append(path)
            train_keys.add(key)
    if train_keys & eval_keys:
        raise AssertionError("prompt overlap detected between train and evaluation splits")
    return train, evaluation


def example(path: Path, length: int) -> tuple[torch.Tensor, torch.Tensor]:
    data = np.load(path)
    ids = np.concatenate([data["traj0_prompt_ids"], data["traj0_response_ids"]])[:length]
    generated = np.concatenate([np.zeros(len(data["traj0_prompt_ids"]), np.int8), data["traj0_response_mask"]])[:length]
    target = np.concatenate([generated[1:], [0]]).astype(bool)  # position t predicts token t+1
    return torch.tensor(ids, dtype=torch.long)[None], torch.tensor(target)[None]


def kl_to_teacher(hidden, teacher_logits, lm_head, mask, chunk: int = 2048):
    """Sum and count of KL(teacher || student) over masked positions, chunked over the sequence."""
    total, count = hidden.new_zeros((), dtype=torch.float32), int(mask.sum())
    for start in range(0, hidden.shape[1], chunk):
        m = mask[:, start:start + chunk]
        if not m.any():
            continue
        student = torch.log_softmax(lm_head(hidden[:, start:start + chunk]).float(), -1)
        teacher = torch.log_softmax(teacher_logits[:, start:start + chunk].to(student.device).float(), -1)
        total = total + ((teacher.exp() * (teacher - student)).sum(-1) * m).sum()
    return total, count


def main(argv: list[str] | None = None) -> None:
    run = json.loads(Path((argv or sys.argv[1:])[0]).read_text())
    out = Path(run["output"])
    if out.exists() and any(out.iterdir()):
        raise FileExistsError(f"refusing to write into non-empty output directory: {out}")

    from transformers import AutoConfig, AutoModelForCausalLM

    from archlab.architectures import qwen35_insertion as insertion

    out.mkdir(parents=True, exist_ok=True)
    student_device, teacher_device = run["student_device"], run["teacher_device"]
    torch.cuda.set_device(torch.device(student_device))  # Triton kernels launch on the current device
    paths = sorted(p for root in run["trajectories"] for p in Path(root).glob("step_*/session-*/trajectory.npz"))
    train, evaluation = split(paths, run["eval_fraction"])
    rng = random.Random(run["seed"])
    evaluation = rng.sample(evaluation, min(run["eval_examples"], len(evaluation)))

    def load(path, device):
        model = AutoModelForCausalLM.from_pretrained(path, dtype=torch.bfloat16, device_map={"": device})
        model.config.use_cache = False
        return model.eval()

    teacher, student = load(run["teacher"], teacher_device), load(run["student"], student_device)
    layer_types = AutoConfig.from_pretrained(run["student"]).get_text_config().layer_types
    sites = insertion.stratified_sites(layer_types, run["site_fraction"])
    if run["mechanism"] != "none":
        config = insertion.InsertionConfig(hidden_size=student.config.get_text_config().hidden_size,
                                           mechanism=run["mechanism"], **run.get("branch", {}))
        insertion.install(student, config, sites, seed=run["seed"])
        counts = insertion.freeze_backbone(student)
        description = insertion.describe(config, sites, layer_types)
    else:  # the untrained parent: evaluation only
        counts, description = {"trainable": 0}, {"sites": []}
    student.gradient_checkpointing_enable()
    (out / "RUN.json").write_text(json.dumps({**run, **counts, **description, "train_trajectories": len(train),
                                              "eval_trajectories": len(evaluation)}, indent=1, default=str) + "\n")

    def teacher_logits(ids):
        with torch.no_grad():
            return teacher(ids.to(teacher_device)).logits

    def evaluate() -> float:
        student.eval()
        total, count = 0.0, 0
        with torch.no_grad():
            for path in evaluation:
                ids, mask = example(path, run["sequence_length"])
                hidden = student.model(ids.to(student_device)).last_hidden_state
                kl, n = kl_to_teacher(hidden, teacher_logits(ids), student.lm_head, mask.to(student_device))
                total, count = total + float(kl), count + n
        student.train()
        return total / max(1, count)

    log = (out / "metrics.jsonl").open("a")

    def record(**fields):
        log.write(json.dumps({"at": time.strftime("%F %T"), **fields}) + "\n")
        log.flush()

    record(step=0, tokens=0, eval_kl=evaluate())
    if run["mechanism"] == "none":
        return
    trainable = [p for p in student.parameters() if p.requires_grad]
    optimizer = torch.optim.AdamW(trainable, lr=run["lr"], betas=(0.9, 0.95), weight_decay=0.0)
    warmup, total_steps = run["warmup_steps"], run["steps"]
    schedule = torch.optim.lr_scheduler.LambdaLR(optimizer, lambda s: min(1.0, (s + 1) / warmup) * 0.5 * (
        1 + math.cos(math.pi * min(1.0, s / total_steps))))
    student.train()
    tokens = 0
    for step in range(1, total_steps + 1):
        ids, mask = example(rng.choice(train), run["sequence_length"])
        if not mask.any():
            continue
        hidden = student.model(ids.to(student_device)).last_hidden_state
        kl, n = kl_to_teacher(hidden, teacher_logits(ids), student.lm_head, mask.to(student_device))
        loss = kl / n
        loss.backward()
        norm = torch.nn.utils.clip_grad_norm_(trainable, run["grad_clip"])
        optimizer.step()
        schedule.step()
        optimizer.zero_grad(set_to_none=True)
        tokens += ids.shape[1]
        if step % run["log_every"] == 0:
            record(step=step, tokens=tokens, train_kl=float(loss), grad_norm=float(norm), lr=schedule.get_last_lr()[0])
        if step % run["eval_every"] == 0 or step == total_steps:
            record(step=step, tokens=tokens, eval_kl=evaluate())
    torch.save({k: v.cpu() for k, v in student.inserted_branches.state_dict().items()}, out / "branches.pt")


if __name__ == "__main__":
    main()
